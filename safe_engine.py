# === SECTION 2: MONTE CARLO DCF ENGINE ===
# MATH, LOGIC & DEFENSE STRATEGY:
# Static DCF models are deterministic—they force you to make a single, fragile guess
# about the future. This engine is probabilistic. It simulates 1,000 macroeconomic
# realities to find the mathematical median, solving for probability rather than certainty.
#
# 1. THE STOCHASTIC SIMULATION (Triangular Tail-Risk):
#    Math: Uses np.random.triangular to heavily weight downside macroeconomic shocks,
#    and np.random.normal for WACC, clipped at 15% to prevent discount rate hallucinations.
#
# 2. DISCOUNTING (Time Value of Money):
#    Math: Future Cash Flow / (1 + WACC)^Year
#
# 3. TERMINAL VALUE BLENDING (The 10-Year Cliff):
#    Math: Averages the Gordon Growth Model [FCF * (1+g) / (WACC - g)] with a
#    standard Exit Multiple [Final EBITDA * Sector Multiple].
#    Safety: Enforces a strict 100bps spread between WACC and Growth to prevent divide-by-zero.
#
# 4. ENTERPRISE-TO-EQUITY BRIDGE (Financials Bypass):
#    Math: Implied Share Price = (Total Enterprise Value - Net Debt) / Shares Outstanding.
#    Defense: Shareholders do not own the whole company; debt-holders own a slice.
#    However, if the sector is Financial Services or Real Estate, debt is raw material
#    (deposits/mortgages), not a leverage penalty, so the Net Debt subtraction is bypassed.
# ==============================================================================

def generate_dcf_model(ticker, sector, current_price, current_fcf, current_ebitda, current_revenue, shares_out, net_debt, base_growth_rate, live_wacc, sharpe_ratio=None, crash_mode=False, roic=None):

    if pd.isna(shares_out) or shares_out <= 0:
        return "N/A (Missing Shares Data)", 0, np.nan

    try:
        if live_wacc > 1.0: live_wacc = live_wacc / 100
        if shares_out < 10000 and pd.notna(current_revenue) and current_revenue > 1000000: shares_out = shares_out * 1000000

        if crash_mode:
            tgr = 0.010
            effective_wacc = max(live_wacc, 0.12)
            base_g = min(max(base_growth_rate / 100, 0.01), 0.10)
        else:
            if pd.notna(base_growth_rate) and base_growth_rate < 0: tgr = 0.00
            elif roic and pd.notna(roic) and roic > 20: tgr = min(0.04, 0.025 + ((roic - 20) * 0.0005))
            else: tgr = 0.025

            effective_wacc = max(live_wacc, 0.08)
            base_g = min(max(base_growth_rate / 100, -0.05), 0.25) if pd.notna(base_growth_rate) else 0.05

        iterations = 1000

        # TRIANGULAR TAIL-RISK (Asymmetric downside shocks)
        rand_g = np.random.triangular(left=max(-0.05, base_g - 0.04), mode=base_g, right=min(0.25, base_g + 0.02), size=iterations)

        rand_wacc = np.clip(np.random.normal(effective_wacc, 0.01, iterations), 0.07, 0.15)

        rand_wacc = np.maximum(rand_wacc, tgr + 0.01)

        sdf_m = 1 / (1 + rand_wacc)
        sdf_volatility = np.std(sdf_m) / np.mean(sdf_m)
        hj_penalty = 0.85 if (sharpe_ratio and pd.notna(sharpe_ratio) and sharpe_ratio > 0 and sdf_volatility < sharpe_ratio) else 1.0

        base_ebitda_mult = sector_exit_multiples.get(sector, 12.0)
        rand_ebitda_mult = np.random.normal(base_ebitda_mult, 1.5, iterations)
        base_sales_mult = sector_sales_multiples.get(sector, 2.0)
        rand_sales_mult = np.random.normal(base_sales_mult, 0.5, iterations)

        implied_prices = []
        burn_rate_mode = pd.isna(current_fcf) or current_fcf <= 0 or pd.isna(current_ebitda) or current_ebitda <= 0

        for i in range(iterations):
            g_start = rand_g[i]
            wacc = rand_wacc[i]

            if wacc <= tgr:
                wacc = tgr + 0.015

            forecast_years = 10 if sector in ['Technology', 'Communication Services'] or (roic and roic > 20) else 5
            g_fade = [g_start - (g_start - tgr) * (yr / forecast_years) for yr in range(1, forecast_years + 1)]

            if burn_rate_mode:
                rev_proj = current_revenue
                for yr in range(forecast_years): rev_proj *= (1 + g_fade[yr])
                terminal_value = rev_proj * rand_sales_mult[i]
                pv_tv = terminal_value / (1 + wacc)**forecast_years
                blended_ev = pv_tv
            else:
                fcf_proj = current_fcf
                ebitda_proj = current_ebitda
                pv_fcf_sum = 0
                for yr in range(forecast_years):
                    fcf_proj *= (1 + g_fade[yr])
                    ebitda_proj *= (1 + g_fade[yr])
                    pv_fcf_sum += fcf_proj / (1 + wacc)**(yr+1)

                tv_gordon = (fcf_proj * (1 + tgr)) / (wacc - tgr)
                pv_tv_gordon = tv_gordon / (1 + wacc)**forecast_years
                ev_gordon = pv_fcf_sum + pv_tv_gordon

                tv_multiple = ebitda_proj * rand_ebitda_mult[i]
                pv_tv_multiple = tv_multiple / (1 + wacc)**forecast_years
                ev_multiple = pv_fcf_sum + pv_tv_multiple
                blended_ev = (ev_gordon + ev_multiple) / 2

            # THE FINANCIALS BYPASS (No Debt Penalty for Banks/REITs)
            if sector in ['Financial Services', 'Real Estate']:
                implied_equity = blended_ev
            else:
                implied_equity = blended_ev - net_debt

            implied_price = (implied_equity / shares_out) * hj_penalty
            implied_prices.append(max(implied_price, 0))

        implied_prices = np.array(implied_prices)
        implied_prices = implied_prices[(implied_prices >= np.percentile(implied_prices, 2)) & (implied_prices <= np.percentile(implied_prices, 98))]

        if len(implied_prices) == 0: return "Error: Invalid MC Projections", 0, np.nan

        mean_implied = np.median(implied_prices)
        prob_undervalued = np.sum(implied_prices > current_price) / len(implied_prices) * 100

        fig = plt.figure(figsize=(7, 4))
        plt.hist(implied_prices, bins=50, color='#3498db', edgecolor='black', alpha=0.7)
        plt.axvline(current_price, color='red', linestyle='dashed', linewidth=2, label=f'Current: ${current_price:.2f}')
        plt.axvline(mean_implied, color='green', linestyle='dashed', linewidth=2, label=f'Mean: ${mean_implied:.2f}')
        plt.title(f"{ticker} Monte Carlo (1,000 Scenarios)", fontsize=12, fontweight='bold')
        plt.legend()
        plt.tight_layout()
        plt.savefig(f"{ticker}_DCF_Chart.png", bbox_inches='tight')
        plt.close(fig)

        return f"Mean: ${mean_implied:.2f} ({prob_undervalued:.0f}% Win)", prob_undervalued, mean_implied

    except Exception as e:
        return f"Error: {e}", 0, np.nan

def run_stress_test(ticker, current_price, current_fcf, shares_out, net_debt, base_g, wacc):
    try:
        scenarios = {
            "Fed_Spike": (base_g, wacc + 0.03),
            "Growth_Shock": (base_g * 0.5, wacc),
            "Crisis": (base_g * 0.2, wacc + 0.04)
        }

        stress_results = {}
        for name, (g, w) in scenarios.items():
            fcf_proj = [current_fcf * (1 + (g/100))**yr for yr in range(1, 6)]
            terminal = (fcf_proj[-1] * 1.02) / (w - 0.02) if w > 0.02 else 0
            pv = sum([fcf_proj[i] / (1+w)**(i+1) for i in range(5)]) + (terminal / (1+w)**5)
            implied_val = (pv - net_debt) / shares_out
            stress_results[name] = round(implied_val, 2)
        return stress_results
    except:
        return {"Fed_Spike": 0, "Growth_Shock": 0, "Crisis": 0}


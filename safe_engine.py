# === SECTION 3: PERFORMANCE & RISK BACKTESTER ===
# MATH, LOGIC & DEFENSE STRATEGY:
# Raw return means nothing without measuring the risk taken to achieve it. This
# module strips away the illusion of luck, measuring the exact mathematical
# efficiency of the asset and proving if historical outperformance is repeatable.
#
# 1. THE VOLATILITY ANCHOR (Beta):
#    Math: Covariance(Stock Returns, Market Returns) / Variance(Market Returns).
#    Defense: Beta measures Systematic Risk (market-wide risk), not Unsystematic Risk
#    (company-specific risk). A Beta of 1.5 means the stock swings 50% harder than
#    the S&P 500. This is used to balance the portfolio; heavy tech allocations must
#    be offset by low-Beta defensive assets to prevent total portfolio blowup.
#
# 2. RISK-ADJUSTED REWARD (Sharpe vs. Sortino Ratio):
#    Math (Sortino): (Annual Return - Risk-Free Rate) / Downside Volatility.
#    Defense: Sharpe unfairly punishes a stock for ALL volatility—including violent
#    moves upward. Sortino is superior for this strategy because it isolates and
#    penalizes only downside volatility. It perfectly aligns with a mandate seeking
#    "positive skewness" (protecting the floor while letting winners run).
#
# 3. LUCK VS. SKILL (Bootstrap Alpha Test):
#    Logic: Randomly resamples 3 years of daily returns into 100 different 6-month windows.
#    Defense: Looking at a 3-year chart to claim "outperformance" is statistically weak
#    (it could be driven by one lucky month). Bootstrapping proves consistency. An 85%
#    win rate means no matter what random day you bought the stock, you had an 85%
#    probability of beating the market over the next 6 months.
#
# 4. THE PAIN THRESHOLD (Max Drawdown / MDD):
#    Math: (Lowest Trough Price - Highest Peak Price) / Highest Peak Price.
#    Defense: Loss is asymmetric—a 50% drawdown requires a 100% gain just to break even.
#    MDD calculates the absolute worst-case historical drop, allowing the portfolio
#    manager to set mathematically justified, ruthless stop-loss floors.
# ==============================================================================



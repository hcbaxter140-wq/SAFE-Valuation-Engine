# MATH, LOGIC & DEFENSE STRATEGY:
# This is the central nervous system of the S.A.F.E. architecture. It removes
# human emotion from capital allocation by calculating exactly what it costs a
# company to operate, how much cash it generates, and exactly how much capital
# we should risk on it.
#
# 1. COST OF EQUITY (CAPM & Blume's Beta):
#    Math: Risk-Free Rate + (Adjusted Beta * Equity Risk Premium)
#    Defense: We do not use raw historical Beta, which can be skewed by anomalies.
#    The engine applies the institutional Blume Adjustment [(0.67 * raw) + (0.33 * 1.0)]
#    because all extreme volatility mathematically mean-reverts toward 1.0 over time.
#
# 2. THE GRAVITY OF THE ASSET (WACC & The Tax Shield):
#    Math: (Equity Weight * CAPM) + (Debt Weight * Debt Cost * (1 - Tax Rate))
#    Defense: The formula multiplies the cost of debt by (1 - Tax Rate). Why?
#    Because corporate interest payments are tax-deductible. The engine correctly
#    prices in the "Corporate Tax Shield," recognizing that smart debt is mathematically
#    cheaper than equity funding.
#
# 3. THE WEALTH CREATOR (ROIC & Economic Value Added):
#    Math: ROIC = NOPAT / (Total Assets - Current Liabilities).
#    Defense: EPS can be easily manipulated via stock buybacks; ROIC cannot be faked.
#    If a company's ROIC does not clear its WACC (a negative EVA spread), it is
#    literally burning cash to exist. The engine hard-codes a rejection (Dual-Hurdle)
#    for any company destroying shareholder wealth.
#
# 4. POSITION SIZING (The Blended Kelly Criterion):
#    Logic: Allocates portfolio percentage based on the mathematical edge.
#    Defense: We don't guess position sizes. The engine utilizes a modified Kelly
#    Criterion, algorithmically scaling the allocation strictly based on the asset's
#    fundamental score, Monte Carlo probability of success, and Sortino downside
#    protection. Big edge = big allocation. No edge = zero allocation.
# ==============================================================================



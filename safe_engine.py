def detect_market_crash(api_key):
    """
    Pulls High-Yield Credit Spreads to detect institutional panic.
    Calculates a 90-day rolling Z-Score. If Z-Score > 2.0, triggers Crash Mode.
    """
    if not api_key or api_key == 'YOUR_FRED_API_KEY_HERE':
        return False

    try:
        fred = Fred(api_key=api_key)
        spreads = fred.get_series('BAMLC0A0CM').dropna()

        if len(spreads) < 90:
            return False

        recent_spreads = spreads.tail(90)
        current_spread = recent_spreads.iloc[-1]
        mean_spread = recent_spreads.mean()
        std_spread = recent_spreads.std()

        z_score = (current_spread - mean_spread) / std_spread if std_spread > 0 else 0

        is_crash = z_score > 2.0

        if is_crash:
            print(f" NOWCAST ALERT: Credit Spreads Spiking (Z-Score: {z_score:.2f}). CRASH MODE ACTIVATED.")
        else:
            print(f" NOWCAST STATUS: Credit Markets Stable (Z-Score: {z_score:.2f}).")

        return is_crash

    except Exception as e:
        print(f"⚠️ Nowcast API Error: {e}")
        return False


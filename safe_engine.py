def run_sentiment_event_study(ticker, event_date, days_before=10, days_after=30):
    """
    Validates the 'Elasticity of Emotion'. Tracks a stock's Cumulative Abnormal Return (CAR)
    before and after a major sentiment shock, stripping away the S&P 500's movement.
    """
    print(f"\n🔬 Initiating Event Study for {ticker} around {event_date}...")
    try:
        start_date = pd.to_datetime(event_date) - pd.Timedelta(days=days_before + 20)
        end_date = pd.to_datetime(event_date) + pd.Timedelta(days=days_after + 20)

        # Pull Stock and Market (SPY) Data
        stock = yf.download(ticker, start=start_date, end=end_date, progress=False)['Close']
        rsp = yf.download('RSP', start=start_date, end=end_date, progress=False)['Close']

        if stock.empty or rsp.empty:
            return "Error: Insufficient historical data."

        # Merge and calculate daily returns
        df = pd.concat([stock, rsp], axis=1).dropna()
        df.columns = ['Stock', 'Market']
        df['Stock_Ret'] = df['Stock'].pct_change()
        df['Market_Ret'] = df['Market'].pct_change()

        # Abnormal Returns (Stock Return - Market Return)
        df['Abnormal_Return'] = df['Stock_Ret'] - df['Market_Ret']
        df = df.dropna()

        event_idx = df.index.get_indexer([pd.to_datetime(event_date)], method='nearest')[0]
        window_start = max(0, event_idx - days_before)
        window_end = min(len(df), event_idx + days_after)

        event_window = df.iloc[window_start:window_end].copy()

        # Cumulative Abnormal Return (CAR)
        event_window['CAR'] = event_window['Abnormal_Return'].cumsum() * 100

        # Create a relative timeline (-10 to +30 days)
        timeline = np.arange(-days_before, len(event_window) - days_before)

        plt.figure(figsize=(10, 5))
        plt.plot(timeline, event_window['CAR'], color='purple', linewidth=2.5, label='Cumulative Abnormal Return (CAR)')
        plt.axvline(0, color='red', linestyle='--', linewidth=2, label='Day Zero (Sentiment Shock)')
        plt.axhline(0, color='black', linestyle='-', linewidth=1)

        plt.fill_between(timeline, event_window['CAR'], 0, where=(event_window['CAR'] > 0), color='green', alpha=0.3)
        plt.fill_between(timeline, event_window['CAR'], 0, where=(event_window['CAR'] < 0), color='red', alpha=0.3)

        plt.title(f"📊 EVENT STUDY: {ticker} Sentiment Shock Absorption", fontweight='bold')
        plt.xlabel("Trading Days Relative to Event")
        plt.ylabel("Abnormal Return vs S&P 500 (%)")
        plt.legend()
        plt.grid(alpha=0.3)

        filename = f"{ticker}_Event_Study.png"
        plt.savefig(filename, bbox_inches='tight')
        plt.show()

        snapback_return = event_window['CAR'].iloc[-1]
        print(f"✅ Event Study Complete. 30-Day Post-Shock CAR: {snapback_return:+.2f}%")

        return snapback_return

    except Exception as e:
        print(f"⚠️ Event Study Error: {e}")
        return None